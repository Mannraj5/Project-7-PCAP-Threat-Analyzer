"""Render an :class:`AnalysisResult` as Markdown, JSON or a terminal summary."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

from .analyzer import AnalysisResult
from .detect import Finding
from .stats import service_name

_SEVERITY_BADGE = {"high": "HIGH", "medium": "MEDIUM", "low": "LOW", "info": "INFO"}


def _utc(ts: float | None) -> str:
    if not ts:
        return "-"
    return datetime.fromtimestamp(ts, timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")


def _human_bytes(n: float) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:,.0f} {unit}" if unit == "B" else f"{n:,.1f} {unit}"
        n /= 1024
    return f"{n} B"  # pragma: no cover


def to_markdown(result: AnalysisResult, top: int = 10) -> str:
    s = result.stats
    name = Path(result.capture).name
    lines = [
        f"# pcapscope report - `{name}`",
        "",
        "| | |",
        "|---|---|",
        f"| SHA-256 | `{result.sha256}` |",
        f"| Packets | {s.packets:,} |",
        f"| Bytes on the wire | {s.bytes:,} ({_human_bytes(s.bytes)}) |",
        f"| First packet | {_utc(s.first)} |",
        f"| Last packet | {_utc(s.last)} |",
        f"| Duration | {s.duration:,.1f} s |",
        f"| Decode errors | {s.decode_errors:,} |",
        f"| Threat findings | {len(result.threats)} |",
        f"| Sensor-health findings | {len(result.sensor_findings)} |",
        "",
    ]

    lines += ["## Threat findings", ""]
    lines += _findings_section(result.threats) or ["No threat findings.", ""]
    lines += ["## Capture health", "",
              "Properties of the capture that cause other tools to under-report.", ""]
    lines += _findings_section(result.sensor_findings) or ["No capture-health issues found.", ""]

    lines += ["## Traffic overview", "", "### Protocol mix", "", "| Protocol | Packets | Share |",
              "|---|---:|---:|"]
    for proto, count in s.protocols.most_common():
        lines.append(f"| {proto} | {count:,} | {count / s.packets:.1%} |")

    lines += ["", "### Top talkers (bytes sent)", "", "| Host | Bytes |", "|---|---:|"]
    for host, count in s.talkers.most_common(top):
        lines.append(f"| {host} | {count:,} |")

    lines += ["", "### Top conversations", "", "| Host A | Host B | Service | Bytes |",
              "|---|---|---|---:|"]
    for (a, b, proto, port), count in s.conversations.most_common(top):
        lines.append(f"| {a} | {b} | {service_name(proto, port)} | {count:,} |")

    if s.dns_queries:
        lines += ["", "### Top DNS queries", "", "| Name | Queries |", "|---|---:|"]
        for qname, count in s.dns_queries.most_common(top):
            lines.append(f"| `{qname}` | {count:,} |")

    lines += ["", f"_Generated by pcapscope in {result.elapsed:.2f} s._", ""]
    return "\n".join(lines)


def _findings_section(findings: list[Finding]) -> list[str]:
    lines: list[str] = []
    for i, f in enumerate(findings, 1):
        lines += [
            f"### {i}. [{_SEVERITY_BADGE[f.severity]}] {f.title}",
            "",
            f.summary,
            "",
            f"- **Rule:** `{f.rule}`",
            f"- **Seen:** {_utc(f.first_seen)} -> {_utc(f.last_seen)}",
        ]
        if f.frames:
            frames = ", ".join(str(n) for n in f.frames)
            lines.append(f"- **Sample frames:** {frames} (Wireshark: `frame.number in {{{' '.join(map(str, f.frames))}}}`)")
        for key, value in f.evidence.items():
            if value in (None, [], {}):
                continue
            lines.append(f"- **{_label(key)}:** {_fmt(key, value)}")
        lines.append("")
    return lines


def _label(key: str) -> str:
    if key.endswith("_s"):
        key = key[:-2] + " (s)"
    return key.replace("_", " ").capitalize()


def _fmt(key: str, value) -> str:
    if isinstance(value, list):
        return ", ".join(f"`{v}`" for v in value)
    if isinstance(value, dict):
        return ", ".join(f"`{k}` x{v}" for k, v in value.items())
    if isinstance(value, str):
        return f"`{value}`"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int) and "port" not in key:
        return f"{value:,}"
    return str(value)


def to_json(result: AnalysisResult, top: int = 10) -> str:
    s = result.stats
    doc = {
        "capture": Path(result.capture).name,
        "sha256": result.sha256,
        "summary": {
            "packets": s.packets,
            "bytes": s.bytes,
            "first_seen": s.first,
            "last_seen": s.last,
            "duration_s": round(s.duration, 6),
            "decode_errors": s.decode_errors,
            "protocols": dict(s.protocols.most_common()),
            "top_talkers": [{"host": h, "bytes": b} for h, b in s.talkers.most_common(top)],
            "top_conversations": [
                {"a": a, "b": b, "protocol": p, "service_port": port, "bytes": n}
                for (a, b, p, port), n in s.conversations.most_common(top)
            ],
            "top_dns_queries": [{"name": q, "count": n} for q, n in s.dns_queries.most_common(top)],
        },
        "findings": [asdict(f) for f in result.findings],
        "elapsed_s": round(result.elapsed, 3),
    }
    return json.dumps(doc, indent=2)


def to_terminal(result: AnalysisResult) -> str:
    s = result.stats
    out = [
        f"{Path(result.capture).name}: {s.packets:,} packets, {_human_bytes(s.bytes)}, "
        f"{s.duration:,.1f} s  [{result.elapsed:.2f} s to analyse]",
    ]
    if not result.findings:
        out.append("  no findings")
    for f in result.findings:
        tag = "sensor" if f.category == "sensor" else f.severity
        out.append(f"  [{tag.upper():>6}] {f.title}")
    return "\n".join(out)
